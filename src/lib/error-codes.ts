/**
 * Shared error codes.
 *
 * Server functions return plain `Error` messages (the transport contract) but
 * the messages themselves come from this map so the client can compare against
 * a constant instead of a hand-typed string. Any new failure mode that a UI
 * needs to branch on belongs here.
 */
export const ERROR_CODES = {
	UNAUTHORIZED: "UNAUTHORIZED",
	INTERNAL_ERROR: "INTERNAL_ERROR",

	ORGANIZATION_NOT_FOUND: "ORGANIZATION_NOT_FOUND",
	BRANCH_NOT_FOUND: "BRANCH_NOT_FOUND",
	USER_NOT_FOUND: "USER_NOT_FOUND",
	USER_ALREADY_ACTIVATED: "USER_ALREADY_ACTIVATED",
	STUDENT_NOT_FOUND: "STUDENT_NOT_FOUND",

	INVITE_NOT_FOUND: "INVITE_NOT_FOUND",
	INVITE_ALREADY_USED: "INVITE_ALREADY_USED",
	INVITE_EXPIRED: "INVITE_EXPIRED",
	INVITE_NOT_ACTIVE: "INVITE_NOT_ACTIVE",
	INVITE_USER_MISSING: "INVITE_USER_MISSING",
	ACCOUNT_ALREADY_ACTIVATED: "ACCOUNT_ALREADY_ACTIVATED",

	REQUEST_NOT_FOUND: "REQUEST_NOT_FOUND",
	REQUEST_ALREADY_PENDING: "REQUEST_ALREADY_PENDING",
	REQUEST_ALREADY_REVIEWED: "REQUEST_ALREADY_REVIEWED",

	COURSE_CODE_TAKEN: "COURSE_CODE_TAKEN",
	COURSE_NOT_FOUND: "COURSE_NOT_FOUND",

	NOTICE_NOT_FOUND: "NOTICE_NOT_FOUND",
	EVENT_NOT_FOUND: "EVENT_NOT_FOUND",
	EVENT_START_REQUIRED: "EVENT_START_REQUIRED",
	CLUB_NOT_FOUND: "CLUB_NOT_FOUND",

	CONTACT_RATE_LIMITED: "CONTACT_RATE_LIMITED",
	CONTACT_INVALID_SUBMISSION: "CONTACT_INVALID_SUBMISSION",
} as const;

export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

const ERROR_CODE_SET: ReadonlySet<string> = new Set(Object.values(ERROR_CODES));

export function isErrorCode(value: string): value is ErrorCode {
	return ERROR_CODE_SET.has(value);
}
